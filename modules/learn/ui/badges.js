const mirror = (row) => row + [...row].reverse().join('');
export const BADGES = Object.freeze(Object.fromEntries(Object.entries(DEFS).map(([id, d]) => [id, Object.freeze({
  name: d.name,
  palette: Object.freeze(d.palette),
  rows: Object.freeze(d.half.map(mirror)),
})])));

// An SVG string for one rank: one <rect> per horizontal run of same-colour pixels. Unknown id gives the Iron badge.
export function badgeSvg(tierId, size = 64) {
  const id = Object.hasOwn(BADGES, tierId) ? tierId : 'iron';
  const { name, palette, rows } = BADGES[id];
  let rects = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      const ch = row[x];
      let end = x + 1;
      while (end < row.length && row[end] === ch) end++;
      if (ch !== '.') rects += `<rect x="${x}" y="${y}" width="${end - x}" height="1" fill="${palette[ch]}"/>`;
      x = end;
    }
  });
  const n = Number(size) > 0 ? Number(size) : 64;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${BADGE_GRID} ${BADGE_GRID}" width="${n}" height="${n}" shape-rendering="crispEdges" role="img" aria-label="${name} rank badge">${rects}</svg>`;
}
